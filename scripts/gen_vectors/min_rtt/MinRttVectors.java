// The first gradient rule's vectors, from Netflix concurrency-limits itself: each scenario's
// settings, the samples fed to `GradientLimit`, and the limit it answered after each one. The
// output is src/min_rtt_vectors_wbtest.mbt.
//
//   javac -cp core.jar:slf4j-api.jar MinRttVectors.java      (concurrency-limits-core 0.5.4, slf4j-api)
//   java -cp .:core.jar:slf4j-api.jar MinRttVectors > ../../../src/min_rtt_vectors_wbtest.mbt
//   moon fmt
//
// Probing is off: the reference spreads its probes with ThreadLocalRandom, which no seed
// reaches. The library's own tests cover probing with an injected draw.

import com.netflix.concurrency.limits.limit.GradientLimit;
import com.netflix.concurrency.limits.limit.functions.SquareRootFunction;

import java.util.ArrayList;
import java.util.List;
import java.util.Random;

public final class MinRttVectors {
    static final class Scenario {
        String name;
        int initial = 50, min = 1, max = 1000;
        double smoothing = 0.2, tolerance = 2.0, backoff = 0.9;
        boolean fixed = false;
        int queue = 4;
        long seed;
        int calls = 400;
        double dropShare = 0.02;
        double slowShare = 0.1;

        Scenario(String name, long seed) {
            this.name = name;
            this.seed = seed;
        }
    }

    public static void main(String[] args) {
        List<Scenario> scenarios = new ArrayList<>();
        scenarios.add(new Scenario("preset, probing off", 1));
        Scenario fixed = new Scenario("a fixed queue and a tight tolerance", 2);
        fixed.fixed = true;
        fixed.queue = 10;
        fixed.tolerance = 1.5;
        fixed.smoothing = 0.5;
        fixed.min = 5;
        fixed.max = 200;
        scenarios.add(fixed);
        Scenario drops = new Scenario("frequent drops", 3);
        drops.dropShare = 0.2;
        drops.backoff = 0.5;
        scenarios.add(drops);
        Scenario slow = new Scenario("a service that slows down", 4);
        slow.slowShare = 0.6;
        slow.initial = 200;
        scenarios.add(slow);
        Scenario large = new Scenario("a limit past a thousand", 5);
        large.initial = 1500;
        large.max = 5000;
        large.calls = 600;
        scenarios.add(large);

        StringBuilder out = new StringBuilder();
        out.append("// Code generated by scripts/gen_vectors/min_rtt from Netflix concurrency-limits'\n");
        out.append("// GradientLimit. DO NOT EDIT.\n\n");
        out.append("///|\npriv struct MinRttVector {\n  name : String\n  rule : MinRtt\n");
        out.append("  rtts : Array[Int64]\n  flying : Array[Int32]\n  dropped : Array[Bool]\n  limits : Array[Int32]\n}\n");
        int index = 0;
        for (Scenario s : scenarios) {
            GradientLimit.Builder builder = GradientLimit.newBuilder()
                .initialLimit(s.initial)
                .minLimit(s.min)
                .maxConcurrency(s.max)
                .smoothing(s.smoothing)
                .rttTolerance(s.tolerance)
                .backoffRatio(s.backoff)
                .probeInterval(-1);
            if (s.fixed) {
                builder.queueSize(s.queue);
            } else {
                builder.queueSize(SquareRootFunction.create(s.queue));
            }
            GradientLimit limit = builder.build();
            Random random = new Random(s.seed);
            List<Long> rtts = new ArrayList<>();
            List<Integer> flying = new ArrayList<>();
            List<Boolean> dropped = new ArrayList<>();
            List<Integer> limits = new ArrayList<>();
            for (int i = 0; i < s.calls; i++) {
                long base = 5_000_000L + random.nextInt(5_000_000);
                long rtt = random.nextDouble() < s.slowShare ? base * (2 + random.nextInt(8)) : base;
                int inflight = Math.max(1, (int) (limit.getLimit() * (0.3 + random.nextDouble())));
                boolean drop = random.nextDouble() < s.dropShare;
                limit.onSample(0L, rtt, inflight, drop);
                rtts.add(rtt);
                flying.add(inflight);
                dropped.add(drop);
                limits.add(limit.getLimit());
            }
            out.append("\n///|\nfn min_rtt_vector_").append(index++).append("() -> MinRttVector {\n  {\n");
            out.append("    name: \"").append(s.name).append("\",\n");
            out.append("    rule: MinRtt::new(initial=").append(s.initial)
                .append(", min=").append(s.min)
                .append(", max=").append(s.max)
                .append(", smoothing=").append(s.smoothing)
                .append(", queue=").append(s.fixed ? "Fixed(" : "Root(").append(s.queue).append(")")
                .append(", tolerance=").append(s.tolerance)
                .append(", probe=0")
                .append(", backoff=").append(s.backoff).append("),\n");
            out.append("    rtts: ").append(join(rtts, "L")).append(",\n");
            out.append("    flying: ").append(join(flying, "")).append(",\n");
            out.append("    dropped: ").append(join(dropped, "")).append(",\n");
            out.append("    limits: ").append(join(limits, "")).append(",\n  }\n}\n");
        }
        out.append("\n///|\nfn min_rtt_vectors() -> Array[MinRttVector] {\n  [");
        for (int i = 0; i < index; i++) {
            out.append(i == 0 ? "" : ", ").append("min_rtt_vector_").append(i).append("()");
        }
        out.append("]\n}\n");
        System.out.print(out);
    }

    static <T> String join(List<T> values, String suffix) {
        StringBuilder sb = new StringBuilder("[");
        for (int i = 0; i < values.size(); i++) {
            sb.append(i == 0 ? "" : ", ").append(values.get(i)).append(suffix);
        }
        return sb.append("]").toString();
    }
}
